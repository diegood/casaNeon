type Key = keyof typeof es | EditorKey;

export type I18nKey = Key;

/** The editor's texts, added by its bundle when it loads (i18n-editor.ts). */
const more: Record<string, string> = {};

export function addTexts(texts: Record<string, string>): void {
  Object.assign(more, texts);
}

/** A text of the interface, with {placeholders} filled in. */
export function translate(_hass: HomeAssistant | undefined, key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = (es as Record<string, string>)[key] ?? more[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function formatNumber(_hass: HomeAssistant | undefined, value: number, digits = 2): string {
  return value.toLocaleString("es", { maximumFractionDigits: digits });
}

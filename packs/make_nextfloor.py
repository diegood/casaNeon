def convert(src: pathlib.Path) -> dict:
    payload = json.loads(src.read_text())
    name, description = PACKS[payload["id"]]
    payload.update(
        format="fp3dpack",
        name=f"{name} (NextFloor)",
        publisher="therealMRBK (NextFloor)",
        description=description,
    )
    for item in payload["items"]:
        item["name"] = {"es": NAMES[item["id"]], **item["name"]}
    return payload


out_dir = pathlib.Path(sys.argv[1])
for src in sorted((pathlib.Path(__file__).parent / "nextfloor").glob("nextfloor.*.json")):
    payload = convert(src)
    target = out_dir / f"{payload['id'].replace('.', '-').replace('_', '-')}.fp3dpack"
    with open(target, "w") as out:
        json.dump({"payload": payload}, out, ensure_ascii=False, separators=(",", ":"))
    print(f"{target.name}: {payload['name']}, {len(payload['items'])} items")
